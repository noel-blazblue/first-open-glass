object MockCatalog {
    val scenes: List<Scene> = listOf(sanlitun, guomao, xihu)
    val defaultSceneId: String = sanlitun.id

    fun sceneById(id: String): Scene {
        return scenes.firstOrNull { it.id == id } ?: scenes.first()
    }

    fun storeById(id: String): Store? {
        scenes.forEach { scene ->
            scene.stores.firstOrNull { it.id == id }?.let { return it }
        }
        return null
    }
}

private fun store(
    id: String,
    name: String,
    shortName: String,
    category: String,
    rating: Double,
    reviewCount: Int,
    avgPrice: Int,
    distanceMeters: Int,
    openNow: Boolean = true,
    hours: String,
    phone: String,
    address: String,
    waitTables: Int,
    waitMinutes: Int,
    tags: List<String>,
    deals: List<Deal>,
    signatures: List<String>,
    suitable: List<String>,
    hasPrivateRoom: Boolean,
    extraAnswers: Map<String, String> = emptyMap(),
): Store {
    val defaultAnswers = mapOf(
        "人均" to "${shortName}人均大约 ${avgPrice} 元。",
        "排队" to if (waitMinutes <= 0) {
            "现在不用排，可以直接坐。"
        } else {
            "现在大约 ${waitTables} 桌，估计还要 ${waitMinutes} 分钟。"
        },
        "招牌" to if (signatures.isEmpty()) {
            "招牌菜可以到店问服务员。"
        } else {
            "招牌是${signatures.joinToString("、")}。"
        },
        "团购" to if (deals.isEmpty()) {
            "这会儿没看到团购。"
        } else {
            deals.joinToString("；") { "${it.title} ${it.price} 元，原价 ${it.original}" }
        },
        "约会" to if ("约会" in suitable) {
            "适合约会，环境还行。"
        } else {
            "更适合随便吃一顿，约会的话可以再看看旁边。"
        },
        "带娃" to if ("带娃" in suitable) {
            "可以带娃，有儿童友好的座位。"
        } else {
            "带小孩可能比较挤，不一定合适。"
        },
        "包间" to if (hasPrivateRoom) "有包间，建议提前打电话订。" else "没有包间。",
        "评价" to "${shortName}${rating} 分，大约 ${reviewCount} 条评价。",
        "营业" to if (openNow) "现在营业中，时间 $hours。" else "现在打烊了，时间 $hours。",
        "导航" to "往前走大约 ${distanceMeters} 米就到，$address。",
    )
    return Store(
        id = id,
        name = name,
        shortName = shortName,
        category = category,
        rating = rating,
        reviewCount = reviewCount,
        avgPrice = avgPrice,
        distanceMeters = distanceMeters,
        openNow = openNow,
        hours = hours,
        phone = phone,
        address = address,
        waitTables = waitTables,
        waitMinutes = waitMinutes,
        tags = tags,
        deals = deals,
        signatures = signatures,
        suitable = suitable,
        hasPrivateRoom = hasPrivateRoom,
        answers = defaultAnswers + extraAnswers,
    )
}

